/**
 * Writes packages/chain/src/abis.ts from Foundry's build output, so the app and scripts use typed
 * ABIs that always match the compiled contracts. Run after `forge build`:
 *
 *   pnpm abis            regenerate
 *   pnpm abis --check    fail if the committed file is out of date (used in CI)
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { contractsDir, repoRoot } from "./lib/tools.ts";

const CONTRACTS = [
  "PolicyVault",
  "VaultFactory",
  "SavingsPool",
  "MockUSDC",
  "HostileToken",
] as const;
const outFile = join(repoRoot, "packages", "chain", "src", "abis.ts");

function abiOf(name: string): unknown[] {
  const artifact = join(contractsDir, "out", `${name}.sol`, `${name}.json`);
  if (!existsSync(artifact))
    throw new Error(`Missing ${artifact}. Run \`forge build\` in contracts/ first.`);
  return (JSON.parse(readFileSync(artifact, "utf8")) as { abi: unknown[] }).abi;
}

const exportName = (name: string) => `${name.charAt(0).toLowerCase()}${name.slice(1)}Abi`;

const body = CONTRACTS.map(
  (name) => `export const ${exportName(name)} = ${JSON.stringify(abiOf(name), null, 2)} as const;`,
).join("\n\n");
const source = `// Generated by scripts/export-abis.ts from contracts/out. Do not edit; run \`pnpm abis\`.\n\n${body}\n`;

if (process.argv.includes("--check")) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== source) {
    console.error("packages/chain/src/abis.ts is out of date with the contracts. Run `pnpm abis`.");
    process.exit(1);
  }
  console.log("ABIs are up to date.");
} else {
  writeFileSync(outFile, source);
  console.log(`Wrote ${outFile}`);
}
