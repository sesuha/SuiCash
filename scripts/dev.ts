/**
 * Local development: anvil + contracts + Vite, with no testnet funds or keys.
 *
 *   1. Start anvil on 127.0.0.1:8545 (chain 31337), or reuse one already running.
 *   2. Deploy the contracts with script/Deploy.s.sol (anvil's unlocked default account).
 *   3. Seed demo data with script/SeedDemo.s.sol once it exists (Phase 2).
 *   4. Write .env.development.local so the app talks to anvil in dev mode.
 *   5. Start the Vite dev server. Ctrl+C stops everything this script started.
 *
 * ERC-4337 features (bundler, paymaster) need the testnet; they are disabled here.
 */
import { spawn, type ChildProcess } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { deploymentToViteEnv, devEnvPath, readDeployment } from "./lib/env.ts";
import {
  ANVIL_CHAIN_ID,
  ANVIL_RPC_URL,
  ANVIL_SENDER,
  contractsDir,
  killTree,
  repoRoot,
  requireTool,
  rpcChainId,
  run,
  toolEnv,
  waitForRpc,
} from "./lib/tools.ts";

const FOUNDRY_HINT = "Install Foundry: https://book.getfoundry.sh/getting-started/installation";
const children: ChildProcess[] = [];

function log(message: string): void {
  console.log(`\x1b[36m[dev]\x1b[0m ${message}`);
}

function stopAll(): void {
  for (const child of children.reverse()) killTree(child);
}

async function startAnvil(): Promise<void> {
  const existing = await rpcChainId(ANVIL_RPC_URL);
  if (existing === ANVIL_CHAIN_ID) {
    log(`Reusing the anvil node already running at ${ANVIL_RPC_URL}.`);
    return;
  }
  if (existing !== null) {
    throw new Error(
      `Port 8545 is serving chain ${existing}, not anvil (${ANVIL_CHAIN_ID}). Stop it first.`,
    );
  }
  log("Starting anvil…");
  // --silent: anvil otherwise prints its well-known dev keys; we never log keys.
  const anvil = spawn(
    "anvil",
    ["--chain-id", String(ANVIL_CHAIN_ID), "--host", "127.0.0.1", "--port", "8545", "--silent"],
    { env: toolEnv(), stdio: "inherit" },
  );
  children.push(anvil);
  anvil.on("exit", (code) => {
    if (code !== null && code !== 0) log(`anvil exited with code ${code}`);
  });
  await waitForRpc(ANVIL_RPC_URL, 30_000);
  log(`anvil is up at ${ANVIL_RPC_URL}.`);
}

async function forgeScript(script: string): Promise<void> {
  await run(
    "forge",
    [
      "script",
      script,
      "--rpc-url",
      ANVIL_RPC_URL,
      "--broadcast",
      "--unlocked",
      "--sender",
      ANVIL_SENDER,
    ],
    // Never let a testnet deployer key from the shell leak into a local run.
    { cwd: contractsDir, env: toolEnv({ DEPLOYER_PRIVATE_KEY: undefined }) },
  );
}

function writeDevEnv(): void {
  const deployment = readDeployment(ANVIL_CHAIN_ID);
  const values: Record<string, string> = {
    VITE_CHAIN_ID: String(ANVIL_CHAIN_ID),
    VITE_RPC_URL: ANVIL_RPC_URL,
    // ERC-4337 runs on the testnet only.
    VITE_BUNDLER_URL: "",
    VITE_PAYMASTER_URL: "",
    ...deploymentToViteEnv(deployment),
  };
  const body = Object.entries(values)
    .map(([key, value]) => `${key}=${value}`)
    .join("\n");
  writeFileSync(
    devEnvPath,
    `# Generated by \`pnpm dev\` for the local anvil chain. Overwritten on every run; do not edit.\n${body}\n`,
  );
  log(`Wrote ${devEnvPath}`);
}

async function main(): Promise<void> {
  requireTool("anvil", FOUNDRY_HINT);
  requireTool("forge", FOUNDRY_HINT);

  await startAnvil();

  log("Deploying contracts (script/Deploy.s.sol)…");
  await forgeScript("script/Deploy.s.sol");

  if (existsSync(join(contractsDir, "script", "SeedDemo.s.sol"))) {
    log("Seeding demo data (script/SeedDemo.s.sol)…");
    await forgeScript("script/SeedDemo.s.sol");
  } else {
    log("No SeedDemo.s.sol yet (added in Phase 2); skipping demo seed.");
  }

  writeDevEnv();

  log("Starting the web app…");
  // pnpm is a .cmd shim on Windows, which Node can only start through a shell.
  const vite = spawn("pnpm --filter @suicash/web dev", {
    cwd: repoRoot,
    env: toolEnv(),
    stdio: "inherit",
    shell: true,
  });
  children.push(vite);
  vite.on("exit", (code) => {
    stopAll();
    process.exit(code ?? 0);
  });
}

for (const signal of ["SIGINT", "SIGTERM"] as const) {
  process.on(signal, () => {
    stopAll();
    process.exit(0);
  });
}

main().catch((error: unknown) => {
  console.error(`\x1b[31m[dev]\x1b[0m ${error instanceof Error ? error.message : String(error)}`);
  stopAll();
  process.exit(1);
});
